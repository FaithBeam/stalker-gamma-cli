using stalker_gamma_cli.Utilities;

namespace stalker_gamma_cli.Tests;

/// <summary>
/// modlist.txt is MO2's list of mods in a profile, edited by the mo2 mod commands
/// </summary>
public class ModListUtilityTests : IDisposable
{
    private readonly TempDir _dir = new();
    private string ModList => _dir.Join("modlist.txt");

    public void Dispose() => _dir.Dispose();

    /// <summary>
    /// The shape MO2 writes: a header comment and CRLF line endings, plus the blank and
    /// whitespace-only lines that hand edits leave behind
    /// </summary>
    private const string MoModList =
        "# This file was automatically generated by Mod Organizer.\r\n"
        + "-End\r\n"
        + "+G.A.M.M.A. End of List_separator\r\n"
        + "\r\n"
        + "-ZCP 1.5d\r\n"
        + "*Unmanaged: TestDLC\r\n"
        + "   \r\n"
        + "-Mags Buyable at Traders\r\n"
        + "+Fluid Aim\r\n";

    [Fact]
    public async Task Reads_each_mods_status()
    {
        await File.WriteAllTextAsync(ModList, MoModList);

        var mods = await ModListUtility.GetModListAsync(ModList);

        Assert.Equal(
            [
                (ModStatus.Disabled, "End"),
                (ModStatus.Enabled, "G.A.M.M.A. End of List_separator"),
                (ModStatus.Disabled, "ZCP 1.5d"),
                (ModStatus.Unmanaged, "Unmanaged: TestDLC"),
                (ModStatus.Disabled, "Mags Buyable at Traders"),
                (ModStatus.Enabled, "Fluid Aim"),
            ],
            mods.Select(x => (x.Status, x.Name))
        );
    }

    [Fact]
    public async Task Saving_keeps_every_mod_and_its_status()
    {
        await File.WriteAllTextAsync(ModList, MoModList);
        var mods = await ModListUtility.GetModListAsync(ModList);
        mods.Single(x => x.Name == "Mags Buyable at Traders").Status = ModStatus.Enabled;

        await ModListUtility.SaveModListAsync(ModList, mods);

        Assert.Equal(
            [
                "-End",
                "+G.A.M.M.A. End of List_separator",
                "-ZCP 1.5d",
                "*Unmanaged: TestDLC",
                "+Mags Buyable at Traders",
                "+Fluid Aim",
            ],
            await File.ReadAllLinesAsync(ModList)
        );
    }

    [Fact]
    public async Task Saving_and_reading_again_changes_nothing()
    {
        await File.WriteAllTextAsync(ModList, MoModList);
        var mods = await ModListUtility.GetModListAsync(ModList);

        await ModListUtility.SaveModListAsync(ModList, mods);
        var reread = await ModListUtility.GetModListAsync(ModList);

        Assert.Equal(mods.Select(x => (x.Status, x.Name)), reread.Select(x => (x.Status, x.Name)));
    }

    [Fact]
    public async Task Mod_names_keep_trailing_spaces()
    {
        // GAMMA has mods like "G.A.M.M.A. FDDA Rework " and MO2 matches the name exactly
        await File.WriteAllTextAsync(ModList, "-G.A.M.M.A. FDDA Rework \r\n");

        var mod = Assert.Single(await ModListUtility.GetModListAsync(ModList));

        Assert.Equal("G.A.M.M.A. FDDA Rework ", mod.Name);
    }

    [Fact]
    public async Task Missing_file_is_an_error() =>
        await Assert.ThrowsAsync<FileNotFoundException>(() =>
            ModListUtility.GetModListAsync(_dir.Join("missing.txt"))
        );
}
